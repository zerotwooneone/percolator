using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Percolator.SourceGenerators;

[Generator]
public sealed class DomainEventMapperGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "Percolator.SourceGenerators.MapFromDomainEventAttribute";

    private const string MapFromDomainEventAttributeSource = @"// <auto-generated/>
#nullable enable

namespace Percolator.SourceGenerators;

[global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
internal sealed class MapFromDomainEventAttribute : global::System.Attribute
{
    public global::System.Type DomainEventType { get; }

    public MapFromDomainEventAttribute(global::System.Type domainEventType)
    {
        DomainEventType = domainEventType;
    }
}
";

    private static readonly DiagnosticDescriptor TargetMustBePartialDiagnostic = new(
        id: "PERC201",
        title: "[MapFromDomainEvent] target must be partial",
        messageFormat: "The type '{0}' must be declared as a partial record",
        category: "Percolator.SourceGenerators",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor TargetMustBeRecordDiagnostic = new(
        id: "PERC204",
        title: "[MapFromDomainEvent] target must be a record",
        messageFormat: "The type '{0}' must be declared as a record (not a plain class or struct) to participate in domain event mapping",
        category: "Percolator.SourceGenerators",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DomainEventTypeRequiredDiagnostic = new(
        id: "PERC203",
        title: "[MapFromDomainEvent] domain event type required",
        messageFormat: "The attribute [MapFromDomainEvent] on '{0}' must specify a valid domain event type",
        category: "Percolator.SourceGenerators",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly SymbolDisplayFormat TypeFormat = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
                              SymbolDisplayMiscellaneousOptions.UseSpecialTypes |
                              SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource(
                "MapFromDomainEventAttribute.g.cs",
                SourceText.From(MapFromDomainEventAttributeSource, Encoding.UTF8));
        });

        var candidates = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                fullyQualifiedMetadataName: AttributeMetadataName,
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, _) => (TypeDeclarationSyntax)ctx.TargetNode)
            .Where(static r => r is not null);

        var compilationAndCandidates = context.CompilationProvider.Combine(candidates.Collect());

        context.RegisterSourceOutput(compilationAndCandidates, static (spc, pair) =>
        {
            Execute(spc, pair.Left, pair.Right);
        });
    }

    private static void Execute(SourceProductionContext context, Compilation compilation, ImmutableArray<TypeDeclarationSyntax> records)
    {
        if (records.IsDefaultOrEmpty)
            return;

        var validMappings = new List<(INamedTypeSymbol TargetType, INamedTypeSymbol DomainEventType)>();

        foreach (var syntax in records.Distinct())
        {
            var semanticModel = compilation.GetSemanticModel(syntax.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(syntax) is not INamedTypeSymbol targetSymbol)
                continue;

            if (!targetSymbol.IsRecord)
            {
                context.ReportDiagnostic(Diagnostic.Create(TargetMustBeRecordDiagnostic, syntax.GetLocation(), targetSymbol.Name));
                continue;
            }

            if (!IsPartial(syntax))
            {
                context.ReportDiagnostic(Diagnostic.Create(TargetMustBePartialDiagnostic, syntax.GetLocation(), targetSymbol.Name));
                continue;
            }

            var attr = targetSymbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == AttributeMetadataName);
            if (attr is null || attr.ConstructorArguments.Length == 0 || attr.ConstructorArguments[0].Value is not INamedTypeSymbol domainEventSymbol)
            {
                context.ReportDiagnostic(Diagnostic.Create(DomainEventTypeRequiredDiagnostic, syntax.GetLocation(), targetSymbol.Name));
                continue;
            }

            validMappings.Add((targetSymbol, domainEventSymbol));
            GenerateMappingClass(context, compilation, targetSymbol, domainEventSymbol);
        }

        if (validMappings.Count > 0)
        {
            GenerateExtensionsClass(context, validMappings);
        }
    }

    private static void GenerateMappingClass(SourceProductionContext context, Compilation compilation, INamedTypeSymbol targetSymbol, INamedTypeSymbol domainEventSymbol)
    {
        var targetNamespace = targetSymbol.ContainingNamespace.IsGlobalNamespace
            ? null
            : targetSymbol.ContainingNamespace.ToDisplayString();

        var targetTypeName = targetSymbol.Name;
        var domainEventFullName = domainEventSymbol.ToDisplayString(TypeFormat);

        var existingTargetProps = new HashSet<string>(
            targetSymbol.GetMembers().OfType<IPropertySymbol>().Select(p => p.Name),
            StringComparer.Ordinal);

        var domainProps = domainEventSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => p.DeclaredAccessibility == Accessibility.Public && !p.IsStatic && p.GetMethod is not null)
            .ToList();

        var propertiesToEmit = new StringBuilder();
        var assignmentStatements = new StringBuilder();

        var targetConstructors = targetSymbol.Constructors
            .Where(c => c.DeclaredAccessibility == Accessibility.Public || c.DeclaredAccessibility == Accessibility.Internal)
            .ToList();

        IMethodSymbol? matchingCtor = null;
        var ctorArgs = new List<string>();

        foreach (var ctor in targetConstructors.OrderByDescending(c => c.Parameters.Length))
        {
            if (ctor.Parameters.Length == 0) continue;

            var canSatisfy = true;
            var args = new List<string>();

            foreach (var param in ctor.Parameters)
            {
                var matchingDomainProp = domainProps.FirstOrDefault(p =>
                    string.Equals(p.Name, param.Name, StringComparison.OrdinalIgnoreCase));

                if (matchingDomainProp is null)
                {
                    canSatisfy = false;
                    break;
                }

                var (isVo, innerType, isNullableVo) = InspectValueObject(compilation, matchingDomainProp.Type);
                if (isVo)
                {
                    if (SymbolEqualityComparer.Default.Equals(param.Type, innerType))
                    {
                        args.Add(isNullableVo ? $"domainEvent.{matchingDomainProp.Name}?.Value" : $"domainEvent.{matchingDomainProp.Name}.Value");
                    }
                    else
                    {
                        canSatisfy = false;
                        break;
                    }
                }
                else if (SymbolEqualityComparer.Default.Equals(param.Type, matchingDomainProp.Type))
                {
                    args.Add($"domainEvent.{matchingDomainProp.Name}");
                }
                else
                {
                    canSatisfy = false;
                    break;
                }
            }

            if (canSatisfy)
            {
                matchingCtor = ctor;
                ctorArgs = args;
                break;
            }
        }

        var ctorParamNames = matchingCtor is not null
            ? new HashSet<string>(matchingCtor.Parameters.Select(p => p.Name), StringComparer.OrdinalIgnoreCase)
            : new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var domainProp in domainProps)
        {
            if (ctorParamNames.Contains(domainProp.Name))
                continue;

            var (isVo, innerType, isNullableVo) = InspectValueObject(compilation, domainProp.Type);
            var effectiveType = isVo ? innerType! : domainProp.Type;
            var effectiveTypeStr = effectiveType.ToDisplayString(TypeFormat);

            if (!existingTargetProps.Contains(domainProp.Name))
            {
                propertiesToEmit.AppendLine($"    public {effectiveTypeStr} {domainProp.Name} {{ get; init; }}");

                string valueExpr;
                if (isVo)
                {
                    valueExpr = isNullableVo
                        ? $"domainEvent.{domainProp.Name}?.Value"
                        : $"domainEvent.{domainProp.Name}.Value";
                }
                else
                {
                    valueExpr = $"domainEvent.{domainProp.Name}";
                }

                assignmentStatements.AppendLine($"            {domainProp.Name} = {valueExpr},");
            }
            else
            {
                var targetProp = targetSymbol.GetMembers().OfType<IPropertySymbol>().First(p => p.Name == domainProp.Name);
                if (targetProp.SetMethod is null)
                    continue;

                string valueExpr;
                if (isVo && SymbolEqualityComparer.Default.Equals(targetProp.Type, innerType))
                {
                    valueExpr = isNullableVo
                        ? $"domainEvent.{domainProp.Name}?.Value"
                        : $"domainEvent.{domainProp.Name}.Value";
                }
                else if (SymbolEqualityComparer.Default.Equals(targetProp.Type, domainProp.Type))
                {
                    valueExpr = $"domainEvent.{domainProp.Name}";
                }
                else
                {
                    continue;
                }

                assignmentStatements.AppendLine($"            {domainProp.Name} = {valueExpr},");
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (targetNamespace is not null)
        {
            sb.AppendLine($"namespace {targetNamespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"partial record {targetTypeName}");
        sb.AppendLine("{");

        if (propertiesToEmit.Length > 0)
        {
            sb.Append(propertiesToEmit);
            sb.AppendLine();
        }

        sb.AppendLine($"    public static {targetTypeName} FromDomain({domainEventFullName} domainEvent)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(domainEvent);");
        sb.AppendLine();

        if (matchingCtor is not null)
        {
            var argsStr = string.Join(", ", ctorArgs);
            if (assignmentStatements.Length > 0)
            {
                sb.AppendLine($"        var result = new {targetTypeName}({argsStr})");
                sb.AppendLine("        {");
                sb.Append(assignmentStatements);
                sb.AppendLine("        };");
            }
            else
            {
                sb.AppendLine($"        var result = new {targetTypeName}({argsStr});");
            }
        }
        else
        {
            sb.AppendLine($"        var result = new {targetTypeName}");
            sb.AppendLine("        {");
            sb.Append(assignmentStatements);
            sb.AppendLine("        };");
        }

        sb.AppendLine();
        sb.AppendLine("        CustomMap(domainEvent, ref result);");
        sb.AppendLine("        return result;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    static partial void CustomMap({domainEventFullName} source, ref {targetTypeName} target);");
        sb.AppendLine("}");

        context.AddSource($"{targetSymbol.ToDisplayString().Replace('.', '_')}_MapFromDomainEvent.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateExtensionsClass(SourceProductionContext context, List<(INamedTypeSymbol TargetType, INamedTypeSymbol DomainEventType)> mappings)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Percolator.Application2.Ports;");
        sb.AppendLine();
        sb.AppendLine("public static class DomainEventMapperExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    public static global::Percolator.Application2.Ports.IApplicationEvent? ToApplicationEvent(this global::Percolator.Domain.Common.IDomainEvent domainEvent)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (domainEvent is null) return null;");
        sb.AppendLine();
        sb.AppendLine("        return domainEvent switch");
        sb.AppendLine("        {");

        var distinctMappings = mappings
            .GroupBy(m => m.DomainEventType, SymbolEqualityComparer.Default)
            .Select(g => g.First())
            .ToList();

        foreach (var (targetType, domainEventType) in distinctMappings)
        {
            var domainFullName = domainEventType.ToDisplayString(TypeFormat);
            var targetFullName = targetType.ToDisplayString(TypeFormat);
            sb.AppendLine($"            {domainFullName} e => {targetFullName}.FromDomain(e),");
        }

        sb.AppendLine("            _ => null");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("DomainEventMapperExtensions.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static (bool IsVo, ITypeSymbol? InnerType, bool IsNullable) InspectValueObject(Compilation compilation, ITypeSymbol type)
    {
        var isNullable = false;
        var actualType = type;

        if (type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            isNullable = true;
            actualType = named.TypeArguments[0];
        }

        var valueProp = actualType.GetMembers("Value").OfType<IPropertySymbol>()
            .FirstOrDefault(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public && p.GetMethod is not null);

        if (valueProp is null)
            return (false, null, false);

        var innerType = valueProp.Type;
        if (isNullable && innerType.IsValueType && innerType.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T)
        {
            innerType = compilation.GetSpecialType(SpecialType.System_Nullable_T).Construct(innerType);
        }

        return (true, innerType, isNullable);
    }

    private static bool IsPartial(TypeDeclarationSyntax syntax)
    {
        return syntax.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword));
    }
}
