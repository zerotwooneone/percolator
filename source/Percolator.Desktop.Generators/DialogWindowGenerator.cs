using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Percolator.Desktop.Generators;

[Generator]
public sealed class DialogWindowGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "Percolator.Desktop.Common.Windowing.DialogForAttribute";

    private const string DialogForAttributeSource = @"// <auto-generated/>
#nullable enable

namespace Percolator.Desktop.Common.Windowing;

[global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
internal sealed class DialogForAttribute : global::System.Attribute
{
    public global::System.Type ViewModelType { get; }

    public DialogForAttribute(global::System.Type viewModelType)
    {
        ViewModelType = viewModelType;
    }
}
";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 1. Emit the [DialogFor] marker attribute into the consuming project.
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource("DialogForAttribute.g.cs", SourceText.From(DialogForAttributeSource, Encoding.UTF8));
        });

        // 2. Locate classes decorated with [DialogFor(typeof(TViewModel))].
        var dialogMappings = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (genContext, _) => ExtractMapping(genContext))
            .Where(static m => m is not null)
            .Select(static (m, _) => m!.Value)
            .Collect();

        // 3. Emit the GeneratedDialogRegistry.
        context.RegisterSourceOutput(dialogMappings, static (spc, mappings) =>
        {
            if (mappings.IsEmpty)
            {
                return;
            }

            var source = GenerateRegistrySource(mappings);
            spc.AddSource("GeneratedDialogRegistry.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static (string WindowType, string ViewModelType)? ExtractMapping(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol windowSymbol)
        {
            return null;
        }

        var attributeData = context.Attributes.FirstOrDefault(a =>
            a.AttributeClass?.ToDisplayString() == AttributeMetadataName);

        if (attributeData is null || attributeData.ConstructorArguments.Length == 0)
        {
            return null;
        }

        if (attributeData.ConstructorArguments[0].Value is not INamedTypeSymbol vmSymbol)
        {
            return null;
        }

        var windowFullName = windowSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var vmFullName = vmSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        return (WindowType: windowFullName, ViewModelType: vmFullName);
    }

    private static string GenerateRegistrySource(ImmutableArray<(string WindowType, string ViewModelType)> mappings)
    {
        var sb = new StringBuilder();
        sb.AppendLine(@"// <auto-generated/>
#nullable enable

namespace Percolator.Desktop.Common.Windowing;

internal static class GeneratedDialogRegistry
{
    public static global::Avalonia.Controls.Window CreateDialog(object viewModel)
    {
        if (viewModel is null)
        {
            throw new global::System.ArgumentNullException(nameof(viewModel));
        }

        return viewModel switch
        {");

        // Sort by ViewModel name to ensure deterministic source output.
        var ordered = mappings.OrderBy(m => m.ViewModelType, StringComparer.Ordinal);
        foreach (var mapping in ordered)
        {
            sb.AppendLine($"            {mapping.ViewModelType} => new {mapping.WindowType}(),");
        }

        sb.AppendLine(@"            _ => throw new global::System.InvalidOperationException($""No [DialogFor] window registered for ViewModel type '{viewModel.GetType().FullName}'."")
        };
    }
}");
        return sb.ToString();
    }
}
